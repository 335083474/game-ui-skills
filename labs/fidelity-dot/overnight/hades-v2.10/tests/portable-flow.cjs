/* Recipient-run browser regression; not executed by the package author. */
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const base = path.resolve(process.argv[2]);
  const out = path.resolve(process.argv[3]);
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1528, height: 651 }, acceptDownloads: true });
  const results = [], errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  const check = (name, condition) => results.push({ name, status: condition ? '通过' : '失败' });
  await page.goto('file://' + base + '/prototype.html');
  await page.locator('#edit-heading').fill('PORTABLE TITLE');
  await page.locator('#edit-title').fill('Portable boon');
  await page.locator('#edit-rarity').selectOption('Epic');
  await page.locator('#edit-icon').fill('components/icon-haste-ref.png');
  const downloading = page.waitForEvent('download');
  await page.locator('#editor-export').click();
  const download = await downloading;
  const jsonPath = path.join(out, 'exported-scene.json');
  await download.saveAs(jsonPath);
  check('editor exported edited JSON', JSON.parse(fs.readFileSync(jsonPath, 'utf8')).title === 'PORTABLE TITLE');
  await page.goto('file://' + base + '/scene.html');
  await page.locator('#scene-import').setInputFiles(jsonPath);
  await page.waitForFunction(() => document.getElementById('scene-title').textContent === 'PORTABLE TITLE');
  check('portable import preserves title', await page.locator('#scene-title').textContent() === 'PORTABLE TITLE');
  check('portable import preserves option and rarity', (await page.locator('.title-name').first().textContent()) === 'Portable boon' && (await page.locator('.row').first().getAttribute('class')).includes('epic'));
  check('portable import preserves real icon path', (await page.locator('.boon-icon').first().getAttribute('src')) === 'components/icon-haste-ref.png');
  const invalidPath = path.join(out, 'invalid.json');
  fs.writeFileSync(invalidPath, '{"options":[]}');
  await page.locator('#scene-import').setInputFiles(invalidPath);
  await page.waitForFunction(() => document.getElementById('scene-state').textContent.startsWith('Import rejected'));
  check('invalid import preserves current good data', await page.locator('#scene-title').textContent() === 'PORTABLE TITLE');
  await page.locator('#toggle-notes').click();
  check('dialog receives focus', await page.locator('#close-notes').evaluate(n => document.activeElement === n));
  await page.keyboard.press('Shift+Tab');
  check('backward Tab wraps to last dialog control', await page.locator('#scene-long').evaluate(n => document.activeElement === n));
  await page.keyboard.press('Tab');
  check('forward Tab wraps to first dialog control', await page.locator('#close-notes').evaluate(n => document.activeElement === n));
  await page.keyboard.press('Escape');
  check('Escape closes and restores trigger focus', await page.locator('#notes-panel').isHidden() && await page.locator('#toggle-notes').evaluate(n => document.activeElement === n));
  const shortWide = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  shortWide.options[0].description = 'W'.repeat(100);
  const widePath = path.join(out, 'short-wide.json');
  fs.writeFileSync(widePath, JSON.stringify(shortWide));
  await page.locator('#scene-import').setInputFiles(widePath);
  await page.evaluate(() => document.fonts.ready);
  await page.waitForFunction(() => document.querySelector('.row').dataset.overflow === 'true');
  check('overflow warning measures <110-character wide text', await page.locator('.overflow-note').first().isVisible());
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.screenshot({ path: path.join(out, 'portable-flow.png') });
  check('no script errors', errors.length === 0);
  fs.writeFileSync(path.join(out, 'portable-flow-results.json'), JSON.stringify({ version: 'hades-draft-v2.10', results, errors, scope: 'Input/portable flow only; does not approve visual fidelity' }, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
